import { mkdir, mkdtemp, readFile, readdir, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_INDEX_URL = "https://docs.devin.ai/llms.txt";
const DEFAULT_DOCS_ORIGIN = "https://docs.devin.ai";
const CLI_PATH_PREFIX = "/cli/";
const DOWNLOAD_CONCURRENCY = 8;
const REQUEST_TIMEOUT_MS = 30_000;
const REQUEST_RETRIES = 3;

const GROUP_TITLES = new Map([
  ["", "Getting started & core usage"],
  ["acp", "IDE integration (ACP)"],
  ["extensibility", "Extensibility"],
  ["enterprise", "Enterprise"],
  ["reference", "Reference"],
  ["changelog", "Changelog"],
]);

const scriptPath = fileURLToPath(import.meta.url);
const defaultProjectRoot = path.resolve(path.dirname(scriptPath), "..");

export function parseCliEntries(indexMarkdown, docsOrigin = DEFAULT_DOCS_ORIGIN) {
  const entries = [];
  const paths = new Set();
  const linkPattern = /^\s*-\s+\[([^\]]+)]\(([^)\s]+)\)(?::\s*(.*))?\s*$/gm;

  for (const match of indexMarkdown.matchAll(linkPattern)) {
    const [, title, rawUrl, rawDescription = ""] = match;
    let url;
    try {
      url = new URL(rawUrl);
    } catch {
      continue;
    }

    if (url.origin !== docsOrigin || !url.pathname.startsWith(CLI_PATH_PREFIX)) continue;
    if (url.search || url.hash) {
      throw new Error(`CLI 文档 URL 不应包含查询参数或锚点：${rawUrl}`);
    }

    let localPath;
    try {
      localPath = decodeURIComponent(url.pathname.slice(CLI_PATH_PREFIX.length));
    } catch {
      throw new Error(`CLI 文档 URL 编码无效：${rawUrl}`);
    }

    assertSafeMarkdownPath(localPath, rawUrl);
    if (paths.has(localPath)) {
      throw new Error(`llms.txt 中存在重复的 CLI 文档路径：${localPath}`);
    }

    paths.add(localPath);
    entries.push({
      title: title.trim(),
      description: rawDescription.trim(),
      url: url.href,
      localPath,
    });
  }

  if (entries.length === 0) {
    throw new Error("llms.txt 中未发现任何 /cli/*.md 文档；为避免误删，已中止同步");
  }

  return entries;
}

export function buildRoutingIndex(entries, indexUrl = DEFAULT_INDEX_URL) {
  const groups = new Map();
  for (const entry of entries) {
    const firstDirectory = entry.localPath.includes("/") ? entry.localPath.split("/", 1)[0] : "";
    const groupTitle = GROUP_TITLES.get(firstDirectory) ?? titleFromPathSegment(firstDirectory);
    if (!groups.has(groupTitle)) groups.set(groupTitle, []);
    groups.get(groupTitle).push(entry);
  }

  const lines = [
    "# Devin CLI Knowledge Base Index",
    "",
    "<!-- Generated by `pnpm docs:sync:devin-cli`. Do not edit manually. -->",
    "",
    `The \`docs/devin-cli/\` directory is an exact local mirror of the Devin CLI pages listed in [the official documentation index](${indexUrl}).`,
    "When answering Devin CLI questions, consult the corresponding local mirror document first.",
    "",
    "## Routing index",
  ];

  for (const [groupTitle, groupEntries] of groups) {
    lines.push("", `### ${groupTitle}`, "");
    for (const entry of groupEntries) {
      const description = entry.description ? `: ${entry.description}` : "";
      lines.push(`- [${entry.title}](devin-cli/${entry.localPath})${description}`);
    }
  }

  return `${lines.join("\n")}\n`;
}

export async function syncDevinCliDocs({
  projectRoot = defaultProjectRoot,
  indexUrl = DEFAULT_INDEX_URL,
  docsOrigin = DEFAULT_DOCS_ORIGIN,
  fetchImpl = globalThis.fetch,
  retries = REQUEST_RETRIES,
} = {}) {
  if (typeof fetchImpl !== "function") throw new Error("当前 Node.js 运行时不支持 fetch");

  const docsRoot = path.join(projectRoot, "docs");
  const targetMirror = path.join(docsRoot, "devin-cli");
  const targetIndex = path.join(docsRoot, "devin-cli.md");
  await mkdir(docsRoot, { recursive: true });

  const indexMarkdown = await fetchText(indexUrl, { fetchImpl, retries });
  const entries = parseCliEntries(indexMarkdown, docsOrigin);
  const documents = await downloadDocuments(entries, { fetchImpl, retries });
  const routingIndex = buildRoutingIndex(entries, indexUrl);

  const temporaryRoot = await mkdtemp(path.join(docsRoot, ".devin-cli-sync-"));
  const stagedMirror = path.join(temporaryRoot, "mirror");
  const stagedIndex = path.join(temporaryRoot, "devin-cli.md");

  try {
    for (const entry of entries) {
      const destination = path.join(stagedMirror, ...entry.localPath.split("/"));
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, documents.get(entry.localPath), "utf8");
    }
    await writeFile(stagedIndex, routingIndex, "utf8");

    const existingDocuments = await readMarkdownTree(targetMirror);
    const changes = compareDocuments(existingDocuments, documents);
    const existingIndex = await readOptionalFile(targetIndex);
    const indexChanged = existingIndex !== routingIndex;

    if (changes.added.length === 0 && changes.updated.length === 0 && changes.deleted.length === 0 && !indexChanged) {
      await rm(temporaryRoot, { recursive: true, force: true });
      return { ...changes, unchanged: entries.length, indexChanged: false };
    }

    await publishStagedMirror({ temporaryRoot, stagedMirror, stagedIndex, targetMirror, targetIndex });
    return {
      ...changes,
      unchanged: entries.length - changes.added.length - changes.updated.length,
      indexChanged,
    };
  } catch (error) {
    await rm(temporaryRoot, { recursive: true, force: true });
    throw error;
  }
}

async function downloadDocuments(entries, options) {
  const documents = new Map();
  let nextIndex = 0;
  const workerCount = Math.min(DOWNLOAD_CONCURRENCY, entries.length);

  await Promise.all(
    Array.from({ length: workerCount }, async () => {
      while (nextIndex < entries.length) {
        const entry = entries[nextIndex];
        nextIndex += 1;
        const markdown = await fetchText(entry.url, options);
        documents.set(entry.localPath, markdown);
      }
    }),
  );

  return documents;
}

async function fetchText(url, { fetchImpl, retries }) {
  let lastError;

  for (let attempt = 1; attempt <= retries; attempt += 1) {
    try {
      const response = await fetchImpl(url, {
        headers: { "user-agent": "devin-agent-docs-sync/1.0" },
        signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);

      const text = await response.text();
      if (!text.trim()) throw new Error("响应内容为空");
      if (/^\s*<!doctype\s+html|^\s*<html[\s>]/i.test(text)) throw new Error("响应内容是 HTML，不是 Markdown");
      return text;
    } catch (error) {
      lastError = error;
      if (attempt < retries) await delay(250 * 2 ** (attempt - 1));
    }
  }

  throw new Error(`下载失败（已尝试 ${retries} 次）：${url}：${lastError?.message ?? lastError}`);
}

function assertSafeMarkdownPath(localPath, rawUrl) {
  const segments = localPath.split("/");
  const isUnsafe =
    !localPath.endsWith(".md")
    || path.posix.normalize(localPath) !== localPath
    || segments.some((segment) => !segment || segment === "." || segment === "..")
    || localPath.includes("\\")
    || localPath.includes("\0");
  if (isUnsafe) throw new Error(`CLI 文档路径无效：${rawUrl}`);
}

function titleFromPathSegment(segment) {
  if (!segment) return "Getting started & core usage";
  return segment
    .split("-")
    .filter(Boolean)
    .map((word) => `${word[0]?.toUpperCase() ?? ""}${word.slice(1)}`)
    .join(" ");
}

async function readMarkdownTree(root) {
  const documents = new Map();

  async function visit(directory, prefix = "") {
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch (error) {
      if (error.code === "ENOENT") return;
      throw error;
    }

    for (const entry of entries) {
      const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
      const absolutePath = path.join(directory, entry.name);
      if (entry.isDirectory()) await visit(absolutePath, relativePath);
      else if (entry.isFile() && entry.name.endsWith(".md")) {
        documents.set(relativePath, await readFile(absolutePath, "utf8"));
      }
    }
  }

  await visit(root);
  return documents;
}

function compareDocuments(existing, incoming) {
  const added = [];
  const updated = [];
  const deleted = [];

  for (const [localPath, content] of incoming) {
    if (!existing.has(localPath)) added.push(localPath);
    else if (existing.get(localPath) !== content) updated.push(localPath);
  }
  for (const localPath of existing.keys()) {
    if (!incoming.has(localPath)) deleted.push(localPath);
  }

  return { added: added.sort(), updated: updated.sort(), deleted: deleted.sort() };
}

async function publishStagedMirror({ temporaryRoot, stagedMirror, stagedIndex, targetMirror, targetIndex }) {
  const previousMirror = path.join(temporaryRoot, "previous-mirror");
  const previousIndex = path.join(temporaryRoot, "previous-index.md");
  const state = {
    previousMirror: false,
    newMirror: false,
    previousIndex: false,
    newIndex: false,
  };

  try {
    if (await pathExists(targetMirror)) {
      await rename(targetMirror, previousMirror);
      state.previousMirror = true;
    }
    await rename(stagedMirror, targetMirror);
    state.newMirror = true;

    if (await pathExists(targetIndex)) {
      await rename(targetIndex, previousIndex);
      state.previousIndex = true;
    }
    await rename(stagedIndex, targetIndex);
    state.newIndex = true;

    await rm(temporaryRoot, { recursive: true, force: true });
  } catch (error) {
    const rollbackErrors = [];
    await attemptRollback(async () => {
      if (state.newIndex) await rm(targetIndex, { force: true });
      if (state.previousIndex) await rename(previousIndex, targetIndex);
    }, rollbackErrors);
    await attemptRollback(async () => {
      if (state.newMirror) await rm(targetMirror, { recursive: true, force: true });
      if (state.previousMirror) await rename(previousMirror, targetMirror);
    }, rollbackErrors);

    if (rollbackErrors.length > 0) {
      throw new AggregateError([error, ...rollbackErrors], "发布同步结果失败，且回滚未完全成功");
    }
    throw error;
  }
}

async function attemptRollback(action, errors) {
  try {
    await action();
  } catch (error) {
    errors.push(error);
  }
}

async function pathExists(target) {
  try {
    await stat(target);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

async function readOptionalFile(target) {
  try {
    return await readFile(target, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return undefined;
    throw error;
  }
}

function delay(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

function printSummary(result) {
  console.log(
    `Devin CLI 文档同步完成：新增 ${result.added.length}，更新 ${result.updated.length}，删除 ${result.deleted.length}，未变化 ${result.unchanged}。`,
  );
  for (const [label, paths] of [
    ["新增", result.added],
    ["更新", result.updated],
    ["删除", result.deleted],
  ]) {
    for (const localPath of paths) console.log(`- ${label}：docs/devin-cli/${localPath}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  try {
    printSummary(await syncDevinCliDocs());
  } catch (error) {
    console.error(`Devin CLI 文档同步失败：${error.message}`);
    process.exitCode = 1;
  }
}
